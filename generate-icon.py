# Generates icon.svg: a waving Thai flag on a rounded tile.
# Run from the repository root: python3 tools/generate-icon.py
# The stripes are sampled along a sine wave so they ripple like cloth.
import math

TILE = 64
X0, X1 = 10.0, 54.0          # flag left (pole side) and right edges
Y0, H = 17.0, 30.0           # flag top and height (Thai flag ratio is 2:3)
BAND = H / 6.0               # Thai flag: red 1, white 1, blue 2, white 1, red 1
STEPS = 22

def wave_y(x, base):
    """Vertical offset of the cloth at horizontal position x."""
    t = (x - X0) / (X1 - X0)                 # 0 at the pole, 1 at the free edge
    amp = 0.4 + 1.4 * t                      # waves grow toward the free edge
    return base + amp * math.sin(2 * math.pi * 1.1 * t + 0.6)

def band_polygon(top, bottom):
    """Closed polygon for one stripe between two rows (in flag units)."""
    pts_top = []
    pts_bot = []
    for i in range(STEPS + 1):
        x = X0 + (X1 - X0) * i / STEPS
        pts_top.append((x, wave_y(x, Y0 + top)))
        pts_bot.append((x, wave_y(x, Y0 + bottom)))
    pts = pts_top + list(reversed(pts_bot))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"

def flag_outline():
    pts_top = [(X0 + (X1 - X0) * i / STEPS, wave_y(X0 + (X1 - X0) * i / STEPS, Y0)) for i in range(STEPS + 1)]
    pts_bot = [(X0 + (X1 - X0) * i / STEPS, wave_y(X0 + (X1 - X0) * i / STEPS, Y0 + H)) for i in range(STEPS + 1)]
    pts = pts_top + list(reversed(pts_bot))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"

bands = [
    (0.0, BAND, "#A51931"),          # red
    (BAND, 2 * BAND, "#FFFFFF"),     # white
    (2 * BAND, 4 * BAND, "#241D4F"), # blue (double width, centre)
    (4 * BAND, 5 * BAND, "#FFFFFF"), # white
    (5 * BAND, 6 * BAND, "#A51931"), # red
]

band_paths = "\n".join(
    f'    <path d="{band_polygon(a, b)}" fill="{c}"/>' for a, b, c in bands
)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{TILE}" height="{TILE}" viewBox="0 0 {TILE} {TILE}">
  <!-- Thai flag icon with a gentle wave. Generated by tools/generate-icon.py; edit that script and rerun it to change this file. -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="1" stop-color="#E4EAF5"/>
    </linearGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.35"/>
      <stop offset="0.55" stop-color="#FFFFFF" stop-opacity="0"/>
      <stop offset="1" stop-color="#000000" stop-opacity="0.12"/>
    </linearGradient>
    <clipPath id="flagClip">
      <path d="{flag_outline()}"/>
    </clipPath>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="160%">
      <feDropShadow dx="0" dy="1.5" stdDeviation="1.2" flood-color="#1E2A4A" flood-opacity="0.28"/>
    </filter>
  </defs>

  <!-- rounded tile with a soft border -->
  <rect x="0.5" y="0.5" width="{TILE - 1}" height="{TILE - 1}" rx="14" fill="url(#tile)" stroke="#D5DDEB" stroke-width="1"/>

  <!-- flag: stripes, then a sheen that follows the same cloth shape -->
  <g filter="url(#shadow)">
    <g clip-path="url(#flagClip)">
{band_paths}
      <path d="{flag_outline()}" fill="url(#sheen)"/>
    </g>
  </g>
</svg>
'''
open("icon.svg", "w", encoding="utf-8").write(svg)
print("written", len(svg), "bytes")
